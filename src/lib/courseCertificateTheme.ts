function normalizeLanguage(value: string): string {
  return value.normalize('NFKC').trim().toLowerCase().replace(/[_–—-]+/g, ' ').replace(/\s+/g, ' ');
}

export function certificateCountryCode(language: string): string | null {
  return LANGUAGE_COUNTRIES[normalizeLanguage(language)]
    || LANGUAGE_COUNTRIES[normalizeLanguage(baseLanguage(language))]
    || null;
}

export function courseCertificateTheme(code: string | null, language = ''): string {
  const regional = REGIONAL_THEMES[normalizeLanguage(language)]
    || REGIONAL_THEMES[normalizeLanguage(baseLanguage(language))];
  if (regional) return regional;
  const country = certificateCountryCode(language) || code;
  // Esperanto dan input tak dikenal tidak diberi landmark negara secara acak.
  return CERTIFICATE_COUNTRY_THEMES[country || ''] || 'watercolor-landscape';
}
