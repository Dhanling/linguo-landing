const P: [string, string][] = [
  ["yo", "saya"],
  ["tú", "kamu"],
  ["él / ella / usted", "dia / Anda"],
  ["nosotros", "kami / kita"],
  ["vosotros", "kalian"],
  ["ellos / ustedes", "mereka / Anda semua"],
];
/** enam bentuk berurutan yo … ellos → baris tabel */
const enam = (...bentuk: Segmen[][]): BarisKonjugasi[] =>
  bentuk.map((b, i) => ({ pronomina: P[i][0], arti: P[i][1], bentuk: b }));
/** akar tetap + akhiran persona */
const akhiran = (akar: string, ...ak: string[]) => enam(...ak.map((a): Segmen[] => [[akar, "akar"], [a, "persona"]]));
/** kata bantu dikonjugasi + akar + penanda (participio/gerundio) */
const bantu = (aux: string[], akar: string, penanda: string) =>
  enam(...aux.map((x): Segmen[] => [[x + " ", "bantu"], [akar, "akar"], [penanda, "waktu"]]));

