import { chromium } from '/Users/muhamadlutfiramadhani/.npm/_npx/ad9a3fdbcad992c6/node_modules/playwright-core/index.mjs';
import fs from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const failures = [];
page.on('pageerror', error => failures.push(error.message));
await page.goto('http://localhost:3218/silabus/russian', { waitUntil: 'networkidle', timeout: 120000 });
await page.locator('img[src*="/scenes-v1/"],img[src*="/first-chapter-v1/"]').first().evaluate(i=>i.decode());
const overview = page.getByRole('button', {name:'Baca selengkapnya',exact:true});
if (await overview.count()) { await overview.click(); await page.getByRole('button',{name:'Tutup',exact:true}).click(); }
await page.screenshot({path:'reports/silabus-scenes-v1/russian-desktop.png'});
await page.locator('ol').screenshot({path:'reports/silabus-scenes-v1/russian-cards.png'});
const session = page.locator('button[aria-controls^="russian-A1.1-session-"]').first();
await session.click();
if (await session.getAttribute('aria-expanded') !== 'true') throw Error('Topik sesi tidak terbuka');
await session.click();
if (await session.getAttribute('aria-expanded') !== 'false') throw Error('Topik sesi tidak tertutup');
await page.getByRole('combobox', {name:/Pilih level/}).selectOption('3');
if (!(await page.locator('h2').allTextContents()).some(s=>s.includes('B2'))) throw Error('Level B2 gagal dibuka');
await page.getByRole('button', {name:'B2.2',exact:true}).click();
if (!await page.locator('button[aria-controls^="russian-B2.2-session-"]').count()) throw Error('Chapter B2.2 gagal dibuka');
await page.screenshot({path:'reports/silabus-scenes-v1/russian-b2.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto('http://localhost:3218/silabus/swedish', {waitUntil:'networkidle',timeout:120000});
await page.locator('img[src*="/scenes-v1/"],img[src*="/first-chapter-v1/"]').evaluateAll(images => { for (const image of images) image.loading = 'eager'; });
await page.waitForFunction(() => [...document.querySelectorAll('img[src*="/scenes-v1/"],img[src*="/first-chapter-v1/"]')].every(image => image.complete && image.naturalWidth > 0), {timeout:20000});
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'reports/silabus-scenes-v1/swedish-mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
if(overflow) throw Error('Halaman melebar melebihi viewport mobile');
const broken = await page.locator('img[src*="/scenes-v1/"],img[src*="/first-chapter-v1/"]').evaluateAll(images=>images.filter(i=>!i.complete || i.naturalWidth===0).map(i=>i.src));
if(broken.length) throw Error('Ilustrasi gagal dimuat: '+broken.join(','));
console.log(JSON.stringify({levelSwitch:true,chapterSwitch:true,expandCollapse:true,mobileOverflow:false,brokenImages:broken.length,pageErrors:failures},null,2));
await fs.writeFile('reports/silabus-scenes-v1/browser-result.json',JSON.stringify({levelSwitch:true,chapterSwitch:true,expandCollapse:true,mobileOverflow:false,brokenImages:broken.length,pageErrors:failures},null,2)+'\n');
await browser.close();
